# ---- heroes: 0x72's DungeonTileset II (CC0), pasted as they are ----------------

def strip(char, anim, scale):
    frames = [Image.open(os.path.join(SRC, "0x72_%s_%s_%d.png" % (char, anim, i))).convert("RGBA") for i in range(4)]
    frames = [sticker(f.resize((f.width * scale, f.height * scale), Image.NEAREST), edge=1, shadow=1) for f in frames]
    w, h = frames[0].size
    out = Image.new("RGBA", (w * 4, h), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        out.paste(f, (i * w, 0))
    return out


for hero, char in [("hero_sword", "knight_m"), ("hero_mage", "wizzard_f"), ("hero_thief", "elf_m")]:
    save_sprite(strip(char, "run", 1), hero, 4, 8, offset=[0, -12])
    save_sprite(strip(char, "idle", 2), hero + "_battle", 4, 6)

