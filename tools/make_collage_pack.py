b = ground((108, 128, 74))
sky_and_hills(b, "the-hare-hunt-1560.jpg", (0.0, 0.0, 1.0, 0.25), "summer-1568.jpg", (0.0, 0.30, 1.0, 0.48))
paste(b, sticker(cut("katsushika-hokusai_fuji-blue.jpg", (0.0, 0.1, 1.0, 0.9), (70, 34)), turn=3), (96, 10))
paste(b, sticker(cut("rocket.jpg", (0.38, 0.0, 0.62, 0.95), (20, 52)), turn=-4), (250, 6))
horse = Image.open(os.path.join(SRC, "horse.png")).convert("RGBA").resize((26, 21))
paste(b, sticker(horse), (40, 58))
