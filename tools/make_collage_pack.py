#!/usr/bin/env python3
"""Builds the "collage" art pack: the world is cut and pasted from public-domain
and CC0 images (art/sources/collage, see CREDITS.md there); only the mobs stay
hand-made pixel art (they fall back to the placeholder pack).

    python3 tools/make_collage_pack.py

Every pasted piece keeps a white paper edge and a hard shadow: it must be
obvious that it was copied and pasted. Ids not written here come from the
placeholder pack (Art loads it first).
"""
import json, os, random
from PIL import Image, ImageDraw, ImageEnhance, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art", "sources", "collage")
OUT = os.path.join(ROOT, "art", "packs", "collage")
os.makedirs(OUT, exist_ok=True)
W, H = 320, 180
random.seed(7)
manifest = {"_comment": "Collage pack: generated by tools/make_collage_pack.py from art/sources/collage (credits there). Mobs are not here: they stay hand-made (placeholder pack).",
            "sprites": {}, "backgrounds": {}}


def src(name):
    return Image.open(os.path.join(SRC, name)).convert("RGBA")


def cut(name, box, size=None):
    """Crop a region given in 0..1 coordinates, optionally resized."""
    im = src(name)
    w, h = im.size
    piece = im.crop((int(box[0] * w), int(box[1] * h), int(box[2] * w), int(box[3] * h)))
    if size:
        piece = piece.resize(size, Image.LANCZOS)
    return piece


def oval(piece):
    mask = Image.new("L", piece.size, 0)
    ImageDraw.Draw(mask).ellipse([0, 0, piece.width - 1, piece.height - 1], fill=255)
    out = piece.copy()
    out.putalpha(mask)
    return out


def sticker(piece, edge=1, shadow=1, turn=0.0):
    """White paper edge + hard shadow + a slight crooked angle."""
    a = piece.getchannel("A")
    grown = a
    for _ in range(edge):
        g = Image.new("L", (grown.width + 2, grown.height + 2), 0)
        for dx in (0, 1, 2):
            for dy in (0, 1, 2):
                g.paste(255, (dx, dy), grown)
        grown = g
    pad = shadow
    out = Image.new("RGBA", (grown.width + pad, grown.height + pad), (0, 0, 0, 0))
    out.paste((30, 24, 20, 150), (pad, pad), grown)
    out.paste((250, 248, 240, 255), (0, 0), grown)
    out.paste(piece, (edge, edge), a)
    if turn:
        out = out.rotate(turn, resample=Image.BICUBIC, expand=True)
    return out


def paste(base, piece, xy):
    base.alpha_composite(piece, (int(xy[0]), int(xy[1])))


def ground(tint=(96, 130, 80)):
    g = Image.open(os.path.join(SRC, "grass.png")).convert("L").resize((W, W))
    g = ImageEnhance.Contrast(g).enhance(0.35)
    g = ImageOps.colorize(g, (tint[0] - 30, tint[1] - 30, tint[2] - 30), (tint[0] + 30, tint[1] + 30, tint[2] + 20))
    return g.convert("RGBA").crop((0, 0, W, H))


def sky_and_hills(base, sky_src, sky_box, hills_src, hills_box, horizon=80):
    paste(base, cut(sky_src, sky_box, (W, horizon)), (0, 0))
    hills = cut(hills_src, hills_box, (W + 8, 34))
    paste(base, sticker(hills, edge=1, shadow=1, turn=-0.6), (-4, horizon - 30))


def path_band(base, y):
    road = cut("village-street.jpg", (0.30, 0.78, 0.80, 0.95), (W + 20, 30))
    road = ImageEnhance.Color(road).enhance(0.8)
    paste(base, sticker(road, edge=1, shadow=1, turn=0.8), (-10, y - 16))


def save_bg(base, id):
    base.convert("RGB").save(os.path.join(OUT, id + ".png"))
    manifest["backgrounds"][id] = {"file": id + ".png", "centered": False}


def save_sprite(img, id, frames=1, fps=0, **extra):
    img.save(os.path.join(OUT, id + ".png"))
    e = {"file": id + ".png"}
    if frames > 1:
        e["frames"] = frames
        e["fps"] = fps
    e.update(extra)
    manifest["sprites"][id] = e


# ---- backgrounds ---------------------------------------------------------------
# Messy on purpose: paintings from anywhere, photos with no context, generic free
# pixel art (0x72) dropped on top. The play area (objects, the heroes' lane) stays calm.

LOC = json.load(open(os.path.join(ROOT, "data", "locations.json")))["locations"]


def px(name, scale=1):
    im = Image.open(os.path.join(SRC, "0x72_%s.png" % name)).convert("RGBA")
    return im.resize((im.width * scale, im.height * scale), Image.NEAREST)


def clear_of_objects(loc_id, x, y, w, h, margin=10):
    for o in LOC.get(loc_id, {}).get("objects", []):
        ox, oy = o.get("pos", [-99, -99])
        if x - margin < ox < x + w + margin and y - margin < oy < y + h + margin:
            return False
    return True


def scatter(base, loc_id, names, count, area=(0, 130, W, H), sticky=0.5):
    """Generic pixel bits pasted around, never on top of a game object."""
    tries = 0
    while count > 0 and tries < 400:
        tries += 1
        im = px(random.choice(names))
        x = random.randint(area[0], area[2] - im.width)
        y = random.randint(area[1], area[3] - im.height)
        if not clear_of_objects(loc_id, x, y, im.width, im.height):
            continue
        piece = sticker(im, turn=random.uniform(-8, 8)) if random.random() < sticky else im
        paste(base, piece, (x, y))
        count -= 1


