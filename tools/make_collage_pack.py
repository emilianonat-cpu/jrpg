# ---- heroes: 0x72's DungeonTileset II (CC0), pasted as they are ----------------

def strip(char, anim, scale):
    frames = [Image.open(os.path.join(SRC, "0x72_%s_%s_%d.png" % (char, anim, i))).convert("RGBA") for i in range(4)]
    frames = [sticker(f.resize((f.width * scale, f.height * scale), Image.NEAREST), edge=1, shadow=1) for f in frames]
    w, h = frames[0].size
    out = Image.new("RGBA", (w * 4, h), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        out.paste(f, (i * w, 0))
    return out


for hero, char in [("hero_sword", "knight_m"), ("hero_mage", "wizzard_f"), ("hero_thief", "elf_m")]:
    save_sprite(strip(char, "run", 1), hero, 4, 8, hires=False, offset=[0, -12])
    save_sprite(strip(char, "idle", 2), hero + "_battle", 4, 6, hires=False)

# ---- text: readable fonts (SIL OFL, art/sources/fonts) and paper/ink frames ----------------
# font_main: Atkinson Hyperlegible (made for legibility: every letter shape is distinct),
# font_slime: Patrick Hand (Slayme's verbs, handwritten), font_heroes: VT323 (the Heroes'
# menu, a terminal: the one pixel font left, on purpose).
import shutil
FONTS = os.path.join(ROOT, "art", "sources", "fonts")
for id, name, pixel in [("font_main", "atkinson-hyperlegible", False), ("font_heroes", "vt323", True), ("font_slime", "patrick-hand", False)]:
    shutil.copy(os.path.join(FONTS, name + ".woff"), os.path.join(OUT, name + ".woff"))
    shutil.copy(os.path.join(FONTS, name + "-OFL.txt"), os.path.join(OUT, name + "-OFL.txt"))
    manifest["fonts"][id] = {"file": name + ".woff", "pixel": pixel}


def frame(id, fill, edge, shadow=(0, 0, 0, 0), margin=3, padding=4):
    """12x12 nine-slice: a pasted scrap, paper edge, a hard shadow."""
    img = Image.new("RGBA", (12, 12), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rectangle([1, 1, 11, 11], fill=shadow)
    d.rectangle([0, 0, 10, 10], fill=edge)
    d.rectangle([1, 1, 9, 9], fill=fill)
    img.save(os.path.join(OUT, id + ".png"))
    manifest["ui"][id] = {"file": id + ".png", "margin": margin, "padding": padding}


frame("panel_dialogue", (28, 24, 21, 238), (246, 240, 226, 255), (0, 0, 0, 140))
frame("panel_hud", (28, 24, 21, 200), (246, 240, 226, 200), (0, 0, 0, 90))
frame("panel_slime", (232, 222, 196, 255), (60, 50, 40, 255), (0, 0, 0, 140))
frame("panel_hero_menu", (24, 40, 150, 245), (250, 250, 250, 255), (0, 0, 0, 150))

with open(os.path.join(OUT, "manifest.json"), "w") as f:
    json.dump(manifest, f, indent="\t")
print("collage pack written to", OUT)
