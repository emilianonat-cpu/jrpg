#!/usr/bin/env python3
"""Builds the "collage" art pack: the world is cut and pasted from public-domain
and CC0 images (art/sources/collage, see CREDITS.md there); only the mobs stay
hand-made pixel art (they fall back to the placeholder pack).

    python3 tools/make_collage_pack.py

Every pasted piece keeps a white paper edge and a hard shadow: it must be
obvious that it was copied and pasted. Ids not written here come from the
placeholder pack (Art loads it first).

Pictures are made at 2x (S) and drawn at half size with a smooth filter
("scale": 0.5, "filter": "linear" in the manifest): the collage stays sharp,
not pixelated. Only a few generic pixel bits are pasted on top, chunky on
purpose, and the Heroes stay pixel art. Calm rule: one picture per band, one
or two stickers per screen, and the floor where you play stays quiet so the
things you can touch read first (figure/ground).
"""
import json, os, random
from PIL import Image, ImageDraw, ImageEnhance, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art", "sources", "collage")
OUT = os.path.join(ROOT, "art", "packs", "collage")
os.makedirs(OUT, exist_ok=True)
S = 2  # pictures are made at 2x and drawn at half size (sharp, not pixelated)
W, H = 320 * S, 180 * S
random.seed(7)
manifest = {"_comment": "Collage pack: generated by tools/make_collage_pack.py from art/sources/collage (credits there). Mobs are not here: they stay hand-made (placeholder pack).",
            "sprites": {}, "backgrounds": {}, "ui": {}, "fonts": {}}


def src(name):
    return Image.open(os.path.join(SRC, name)).convert("RGBA")


def cut(name, box, size=None):
    """Crop a region given in 0..1 coordinates, optionally resized."""
    im = src(name)
    w, h = im.size
    piece = im.crop((int(box[0] * w), int(box[1] * h), int(box[2] * w), int(box[3] * h)))
    if size:
        piece = piece.resize(size, Image.LANCZOS)
    return piece


def oval(piece):
    mask = Image.new("L", piece.size, 0)
    ImageDraw.Draw(mask).ellipse([0, 0, piece.width - 1, piece.height - 1], fill=255)
    out = piece.copy()
    out.putalpha(mask)
    return out


def sticker(piece, edge=S, shadow=S, turn=0.0):
    """White paper edge + hard shadow + a slight crooked angle."""
    a = piece.getchannel("A")
    grown = a
    for _ in range(edge):
        g = Image.new("L", (grown.width + 2, grown.height + 2), 0)
        for dx in (0, 1, 2):
            for dy in (0, 1, 2):
                g.paste(255, (dx, dy), grown)
        grown = g
    pad = shadow
    out = Image.new("RGBA", (grown.width + pad, grown.height + pad), (0, 0, 0, 0))
    out.paste((30, 24, 20, 150), (pad, pad), grown)
    out.paste((250, 248, 240, 255), (0, 0), grown)
    out.paste(piece, (edge, edge), a)
    if turn:
        out = out.rotate(turn, resample=Image.BICUBIC, expand=True)
    return out


def paste(base, piece, xy):
    base.alpha_composite(piece, (int(xy[0]), int(xy[1])))


def ground(name, box, tint=(96, 130, 80), contrast=0.65):
    """The floor you play on: a painted texture, washed into one quiet tint."""
    g = cut(name, box, (W, H)).convert("L")
    g = ImageEnhance.Contrast(g).enhance(contrast)
    g = ImageOps.colorize(g, tuple(c - 34 for c in tint), tuple(c + 30 for c in tint)).convert("RGBA")
    shade = Image.linear_gradient("L").resize((W, H)).point(lambda v: v * 70 // 255)
    dark = Image.new("RGBA", (W, H), (20, 26, 18, 255))
    dark.putalpha(shade)
    g.alpha_composite(dark)  # a bit darker toward the bottom: depth without detail
    return g


def band(base, name, box, y, h, turn=0.0, y_from=0):
    """A strip of a painting pasted across the screen (the horizon)."""
    piece = cut(name, box, (W + 12 * S, h))
    paste(base, sticker(piece, turn=turn), (-6 * S, y))


def save_bg(base, id):
    base.convert("RGB").save(os.path.join(OUT, id + ".png"))
    manifest["backgrounds"][id] = {"file": id + ".png", "centered": False, "scale": 1.0 / S, "filter": "linear"}


def save_sprite(img, id, frames=1, fps=0, hires=True, **extra):
    img.save(os.path.join(OUT, id + ".png"))
    e = {"file": id + ".png"}
    if hires:
        e.update({"scale": 1.0 / S, "filter": "linear"})
    if frames > 1:
        e["frames"] = frames
        e["fps"] = fps
    e.update(extra)
    manifest["sprites"][id] = e


# ---- backgrounds ---------------------------------------------------------------
# Paintings from anywhere (Met Open Access CC0, Hokusai, Bruegel), photos with no
# context, a couple of chunky generic pixel bits (0x72). The play area stays calm.

def px(name, scale=S):
    im = Image.open(os.path.join(SRC, "0x72_%s.png" % name)).convert("RGBA")
    return im.resize((im.width * scale, im.height * scale), Image.NEAREST)


def calm(base, y, alpha=30):
    """A soft veil over the floor: the objects you can use must win the contrast."""
    veil = Image.new("RGBA", (W, H - y), (24, 30, 22, alpha))
    paste(base, veil, (0, y))


HORIZON = 80 * S

# The Pool: Hokusai's Goten-yama hill on top; the pool itself is the Great Wave.
b = ground("hr_gotenyama.jpg", (0.0, 0.70, 0.5, 1.0), (92, 126, 84))
band(b, "hr_gotenyama.jpg", (0.0, 0.0, 1.0, 0.52), 0, HORIZON - 4 * S)
calm(b, HORIZON)
paste(b, sticker(oval(cut("coffee.jpg", (0.18, 0.05, 0.82, 0.95), (40 * S, 30 * S))), turn=6), (262 * S, 8 * S))
paste(b, px("crate"), (290 * S, 60 * S))
save_bg(b, "bg_loc_pool")

# The Path: Ruisdael's wheat fields and sky; an astronaut floats over them.
b = ground("hr_ruisdael_trigo.jpg", (0.0, 0.80, 1.0, 1.0), (104, 124, 80))
band(b, "hr_ruisdael_trigo.jpg", (0.0, 0.08, 1.0, 0.62), 0, HORIZON - 4 * S, turn=-0.4)
road = cut("hr_ruisdael_trigo.jpg", (0.30, 0.84, 0.75, 0.98), (W + 20 * S, 22 * S)).convert("L")
road = ImageOps.colorize(ImageEnhance.Contrast(road).enhance(0.4), (112, 98, 76), (150, 134, 104)).convert("RGBA")  # quiet dirt: the shards on it must read
paste(b, sticker(road, turn=0.6), (-10 * S, 98 * S))
calm(b, HORIZON + 20 * S, 50)
paste(b, sticker(oval(cut("astronaut.jpg", (0.0, 0.0, 0.55, 0.62), (28 * S, 32 * S))), turn=-12), (176 * S, 6 * S))
paste(b, px("weapon_rusty_sword"), (240 * S, 160 * S))
save_bg(b, "bg_loc_path")

# The Old Tree: the Heart of the Andes behind, Van Gogh's cypress as the tree.
b = ground("hr_church_andes.jpg", (0.0, 0.75, 0.6, 1.0), (88, 116, 74))
band(b, "hr_church_andes.jpg", (0.0, 0.05, 1.0, 0.55), 0, HORIZON - 4 * S)
calm(b, HORIZON)
tree = cut("hr_van_gogh_cipreses.jpg", (0.10, 0.0, 0.75, 0.80), (52 * S, 92 * S))
paste(b, sticker(tree, turn=2), (150 * S, -4 * S))
paste(b, sticker(oval(cut("chelsea.jpg", (0.30, 0.05, 0.75, 0.75), (30 * S, 26 * S))), turn=9), (20 * S, 8 * S))
paste(b, px("skull"), (300 * S, 100 * S))
save_bg(b, "bg_loc_tree")

# The Field: Bruegel's Harvesters; a rocket parked behind the wheat, a horse.
b = ground("hr_harvesters.jpg", (0.0, 0.62, 0.45, 0.85), (112, 126, 72))
band(b, "hr_harvesters.jpg", (0.0, 0.0, 1.0, 0.40), 0, HORIZON - 4 * S, turn=0.4)
calm(b, HORIZON)
paste(b, sticker(cut("rocket.jpg", (0.38, 0.0, 0.62, 0.95), (18 * S, 48 * S)), turn=-4), (252 * S, 8 * S))
horse = Image.open(os.path.join(SRC, "horse.png")).convert("RGBA").resize((26 * S, 21 * S), Image.LANCZOS)
paste(b, sticker(horse), (20 * S, 56 * S))
save_bg(b, "bg_loc_field")

# Battle: the Heroes' world is a tapestry; a unicorn watches from its garden.
b = ground("hr_cazadores_tapiz.jpg", (0.0, 0.6, 1.0, 1.0), (82, 104, 70))
band(b, "hr_cazadores_tapiz.jpg", (0.0, 0.0, 1.0, 0.62), 0, 104 * S)
paste(b, sticker(cut("hr_unicornio_jardin.jpg", (0.15, 0.30, 0.85, 0.80), (46 * S, 36 * S)), turn=-4), (262 * S, 4 * S))
save_bg(b, "bg_battle_meadow")

# Home: Vermeer's room, a portrait of someone nobody knows here.
b = Image.new("RGBA", (W, H), (60, 46, 36, 255))
paste(b, cut("hr_vermeer_jarra.jpg", (0.0, 0.0, 1.0, 0.56), (W, 100 * S)), (0, 0))
floor = ImageEnhance.Brightness(cut("hr_vermeer_jarra.jpg", (0.05, 0.80, 0.95, 1.0), (W, 80 * S))).enhance(0.5)
paste(b, floor, (0, 100 * S))
paste(b, sticker(cut("grace_hopper.jpg", (0.15, 0.05, 0.85, 0.75), (24 * S, 30 * S)), edge=2 * S, turn=-3), (30 * S, 10 * S))
paste(b, px("ui_heart_full"), (56 * S, 8 * S))
save_bg(b, "bg_home")

# Night: La Farge's nocturne, deep space where the moon should be.
b = ImageEnhance.Brightness(cut("hr_la_farge_nocturno.jpg", (0.14, 0.12, 0.86, 0.52), (W, H))).enhance(0.7)
paste(b, sticker(oval(cut("hubble_deep_field.jpg", (0.3, 0.3, 0.6, 0.65), (30 * S, 30 * S))), turn=5), (250 * S, 14 * S))
save_bg(b, "bg_night")

# Title: Seurat's circus sideshow, dimmed; a gibbon from Sesson in a corner.
b = ImageEnhance.Brightness(cut("hr_seurat_circo.jpg", (0.0, 0.05, 1.0, 0.95), (W, H))).enhance(0.55)
paste(b, sticker(cut("hr_sesson_gibones.jpg", (0.0, 0.0, 0.45, 1.0), (44 * S, 46 * S)), turn=-6), (8 * S, 124 * S))
save_bg(b, "bg_title")

# ---- props (gameplay objects stay readable: pots, coins, seeds are not here) ----

save_sprite(sticker(oval(cut("hr_korin_lirios.jpg", (0.05, 0.30, 0.30, 0.95), (24 * S, 18 * S)))), "bush")
save_sprite(sticker(oval(cut("hr_hoefnagel_bodegon.jpg", (0.25, 0.15, 0.75, 0.70), (16 * S, 20 * S))), turn=3), "mushroom_big")
save_sprite(sticker(oval(cut("hr_wave.jpg", (0.02, 0.15, 0.62, 0.75), (44 * S, 18 * S)))), "pool")
save_sprite(sticker(oval(cut("hr_wave.jpg", (0.0, 0.10, 0.70, 0.80), (84 * S, 26 * S)))), "pool_big")
